#!/usr/bin/env bash
# Copies a composed walkthrough into the web app: the MP4, poster and captions go to public/media/, and the
# chapter list becomes src/lib/walkthrough-chapters.ts for the in-app player.
#
#   BUILD_DIR=/path/outside/the/repo VERSION=v2 ./publish.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
WEB="$(cd "$HERE/.." && pwd)"
: "${BUILD_DIR:?Set BUILD_DIR to the folder compose.sh wrote into}"
: "${VERSION:?Set VERSION, e.g. v2}"
OUT="$BUILD_DIR/$VERSION"
MEDIA="$WEB/public/media"

for f in "$OUT/walkthrough_$VERSION.mp4" "$OUT/walkthrough_${VERSION}_poster.jpg" "$OUT/walkthrough_$VERSION.vtt" "$OUT/chapters.json"; do
  [ -f "$f" ] || { echo "publish.sh: missing $f (run compose.sh first)" >&2; exit 1; }
done
mkdir -p "$MEDIA"
cp "$OUT/walkthrough_$VERSION.mp4" "$MEDIA/walkthrough.mp4"
cp "$OUT/walkthrough_${VERSION}_poster.jpg" "$MEDIA/walkthrough-poster.jpg"
cp "$OUT/walkthrough_$VERSION.vtt" "$MEDIA/walkthrough.vtt"

node - "$OUT/chapters.json" "$WEB/src/lib/walkthrough-chapters.ts" "$VERSION" <<'NODE'
const fs = require("fs");
const [chaptersPath, target, version] = process.argv.slice(2);
const { duration, chapters } = JSON.parse(fs.readFileSync(chaptersPath, "utf8"));
const manifest = {
  url: "/media/walkthrough.mp4",
  poster: "/media/walkthrough-poster.jpg",
  captions: "/media/walkthrough.vtt",
  duration,
  chapters: chapters.map(({ step, label, t }) => ({ step, label, t })),
};
const body = JSON.stringify(manifest, null, 2).replace(/"([a-z]+)":/g, "$1:");
fs.writeFileSync(
  target,
  `// Generated by apps/web/walkthrough/publish.sh from the ${version} build. Do not edit by hand.\n` +
    `import type { WalkthroughManifest } from "@/lib/walkthrough";\n\n` +
    `export const WALKTHROUGH = ${body} as const satisfies WalkthroughManifest;\n\n` +
    `export type WalkthroughStep = (typeof WALKTHROUGH.chapters)[number]["step"];\n`
);
console.log(`wrote ${target}: ${manifest.chapters.length} chapters, ${duration} s`);
NODE

echo "copied $VERSION into $MEDIA ($(du -h "$MEDIA/walkthrough.mp4" | cut -f1))"
